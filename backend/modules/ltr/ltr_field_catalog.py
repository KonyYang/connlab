from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class ReadinessSeverity(StrEnum):
    """Readiness handling policy for an LTR field."""

    BLOCKER = "BLOCKER"
    REVIEW_REQUIRED = "REVIEW_REQUIRED"
    PLACEHOLDER_ALLOWED = "PLACEHOLDER_ALLOWED"


@dataclass(frozen=True, slots=True)
class LtrFieldDefinition:
    """Definition of one LTR readiness field."""

    key: str
    display_label: str
    source_paths: tuple[str, ...]
    fallback_policy: str
    severity: ReadinessSeverity
    placeholder_policy: str | None
    operator_action: str


