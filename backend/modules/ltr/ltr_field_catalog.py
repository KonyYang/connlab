def get_ltr_field_catalog() -> tuple[LtrFieldDefinition, ...]:
    """Return the authoritative LTR readiness field catalog."""
    return LTR_FIELD_CATALOG


def get_ltr_field_definition(key: str) -> LtrFieldDefinition:
    """Return one field definition by canonical key."""
    for definition in LTR_FIELD_CATALOG:
        if definition.key == key:
            return definition
    raise KeyError(f"Unknown LTR readiness field key: {key}")
