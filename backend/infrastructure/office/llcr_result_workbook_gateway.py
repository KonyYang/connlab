PARSER_PROFILE_VERSION = "connlab-llcr-macro-v1"
_REQUIREMENT = re.compile(
    r"(?P<comparator><=|≤|<)\s*(?P<limit>[+-]?\d+(?:\.\d+)?)\s*"
    r"(?P<unit>m(?:ohm|Ω|Ω)|(?:u|µ|μ)(?:ohm|Ω|Ω)|(?:ohm|Ω|Ω))",
    re.IGNORECASE,
)


@dataclass(frozen=True, slots=True)
class LlcrWorkbookInspection:
    """Typed evidence returned by the Excel adapter."""

    parser_profile_version: str
    detected_sheets: tuple[str, ...]
    entries: tuple[LlcrResultEntry, ...]
    diagnostics: tuple[LlcrImportDiagnostic, ...]


class LlcrResultWorkbookGateway:
    """Inspect only the workbook structure generated by ConnLab LLCR output."""

    def inspect(
        self,
        *,
        source_path: Path,
        projection: LlcrCrRecordProjection,
    ) -> LlcrWorkbookInspection:
        source = Path(source_path)
        if source.suffix.lower() != ".xlsx" or not source.is_file():
            return _blocked("unsupported_source_file", "Select an existing .xlsx LLCR workbook.")
        if projection.status not in {"ready", "partial_compatible", "complete"}:
            return _blocked(
                "confirmed_matrix_llcr_not_ready",
                "The Active Confirmed Matrix does not have a ready LLCR record projection.",
            )
        if projection.record_type != "llcr":
            return _blocked("unsupported_record_type", "Only LLCR workbooks are supported.")
        mapping_diagnostics = _validate_projection_mapping_uniqueness(projection)
        if mapping_diagnostics:
            return LlcrWorkbookInspection(
                PARSER_PROFILE_VERSION,
                (),
                (),
                tuple(mapping_diagnostics),
            )
        authority_diagnostics = _projection_authority_diagnostics(projection)

        try:
            workbook = load_workbook(source, data_only=False, read_only=False)
        except (BadZipFile, InvalidFileException, OSError, ValueError):
            return _blocked(
                "unsupported_workbook_structure",
                "The selected file is not a readable ConnLab LLCR .xlsx workbook.",
            )
        try:
            diagnostics = _validate_workbook_contract(workbook)
            if diagnostics:
                return LlcrWorkbookInspection(
                    PARSER_PROFILE_VERSION,
                    tuple(workbook.sheetnames),
                    (),
                    tuple(authority_diagnostics + diagnostics),
                )
            entries, parse_diagnostics = _extract_entries(workbook, projection)
            if parse_diagnostics:
                return LlcrWorkbookInspection(
                    PARSER_PROFILE_VERSION,
                    tuple(workbook.sheetnames),
                    (),
                    tuple(authority_diagnostics + parse_diagnostics),
                )
            return LlcrWorkbookInspection(
                PARSER_PROFILE_VERSION,
                tuple(workbook.sheetnames),
                tuple(entries),
                tuple(authority_diagnostics),
            )
        finally:
            workbook.close()


class LocalLlcrImportSourceStore:
    """Contain uploaded preview sources under ConnLab-managed temporary storage."""

    def __init__(self, root: Path) -> None:
        self._root = Path(root)

    def stage(self, *, preview_id: str, file_name: str, content: bytes) -> Path:
        if not content:
            raise ValueError("The selected LLCR workbook is empty.")
        folder = self._root / preview_id
        folder.mkdir(parents=True, exist_ok=False)
        target = folder / "source.xlsx"
        temporary = folder / f".{uuid4().hex}.tmp"
        try:
            temporary.write_bytes(content)
            os.replace(temporary, target)
        finally:
            temporary.unlink(missing_ok=True)
        return target

    def remove(self, preview_id: str) -> None:
        folder = self._root / preview_id
        if folder.is_dir() and folder.parent.resolve() == self._root.resolve():
            shutil.rmtree(folder)


def _validate_workbook_contract(workbook) -> list[LlcrImportDiagnostic]:
    if "Summary" not in workbook.sheetnames:
        return [_diagnostic("unsupported_workbook_structure", "LLCR Summary sheet is missing.")]
    summary = workbook["Summary"]
    if _text(summary["A1"].value) != "Test Step" or not _text(summary["C1"].value):
        return [_diagnostic("unsupported_workbook_structure", "LLCR Summary headers are not supported.")]
    return []


def _validate_projection_mapping_uniqueness(
    projection: LlcrCrRecordProjection,
) -> list[LlcrImportDiagnostic]:
    seen: set[tuple[str, str, str, str]] = set()
    for section in projection.sections:
        category_key = (
            section.category_id
            or section.record_prefix
            or section.category_label
            or "Points"
        ).strip().casefold()
        for stage in section.stages:
            key = (
                category_key,
                section.confirmed_group_id,
                stage.confirmed_row_id,
                stage.source_step.strip(),
            )
            if key in seen:
                return [
                    _diagnostic(
                        "duplicate_mapping",
                        "The LLCR projection maps the same category, Group, and Step more than once.",
                        section.group_label,
                        stage.source_step,
                    )
                ]
            seen.add(key)
    return []


def _projection_authority_diagnostics(
    projection: LlcrCrRecordProjection,
) -> list[LlcrImportDiagnostic]:
    diagnostics = [
        LlcrImportDiagnostic(
            code=item.code,
            severity="blocked",
            message=item.message,
        )
        for item in projection.diagnostics
    ]
    if projection.status == "partial_compatible" and not diagnostics:
        diagnostics.append(
            _diagnostic(
                "measurement_plan_omission",
                "The effective LLCR measurement plan omits one or more Matrix targets.",
            )
        )
    return diagnostics


def _extract_entries(workbook, projection: LlcrCrRecordProjection):
    grouped_sections: dict[str, list] = {}
    for section in projection.sections:
        key = section.category_id or section.record_prefix or section.category_label or "Points"
        grouped_sections.setdefault(key, []).append(section)

    accumulators: dict[tuple[str, str, str], dict] = {}
    diagnostics: list[LlcrImportDiagnostic] = []
    used_sheet_names = {"Summary"}
    for sections in grouped_sections.values():
        sheet_name = _sheet_name(
            sections[0].record_prefix or sections[0].category_label or "Points",
            used_sheet_names,
        )
        used_sheet_names.add(sheet_name)
        if sheet_name not in workbook.sheetnames:
            diagnostics.append(
                _diagnostic(
                    "expected_sheet_missing",
                    f"Expected LLCR sheet {sheet_name} is missing.",
                )
            )
            continue
        sheet = workbook[sheet_name]
        if _text(sheet["A1"].value).replace("Ω", "Ω") != "unit:mΩ" or _text(sheet["B1"].value) != "Resistance":
            diagnostics.append(
                _diagnostic(
                    "unsupported_workbook_structure",
                    f"Sheet {sheet_name} is not a supported ConnLab LLCR record sheet.",
                )
            )
            continue
        max_samples = max(section.sample_count for section in sections)
        corrected_start = (4 + max_samples - 1) + 6
        delta_start = corrected_start + max_samples if projection.delta_r_enabled else None
        bulk = _bulk_average(sheet)
        if bulk is None:
            diagnostics.append(
                _diagnostic(
                    "bulk_resistance_missing",
                    f"Sheet {sheet_name} requires bulk resistance values in B2:B4.",
                )
            )
            continue
        current_row = 10
        for section in sections:
            points = _section_points(section)
            group_start = current_row
            initial_values: dict[tuple[int, str], Decimal] = {}
            for stage_index, stage in enumerate(section.stages):
                stage_start = current_row
                expected_stage_label = _record_stage_label(stage.label, stage_index)
                if stage_index == 0 and _normalized_group(sheet.cell(group_start, 1).value) != _normalized_group(section.group_label):
                    diagnostics.append(
                        _diagnostic(
                            "group_mapping_conflict",
                            f"Sheet {sheet_name} does not match Group {section.group_label}.",
                            section.group_label,
                            stage.source_step,
                        )
                    )
                    break
                if _text(sheet.cell(stage_start, 2).value) != expected_stage_label:
                    diagnostics.append(
                        _diagnostic(
                            "stage_mapping_conflict",
                            f"Sheet {sheet_name} stage {expected_stage_label} cannot be matched.",
                            section.group_label,
                            stage.source_step,
                        )
                    )
                    break
                requirement = _parse_requirement(
                    stage.requirement,
                    stage_index=stage_index,
                )
                if requirement is None:
                    diagnostics.append(
                        _diagnostic(
                            "requirement_not_interpretable",
                            f"Requirement for Group {section.group_label} Step {stage.source_step} cannot be interpreted.",
                            section.group_label,
                            stage.source_step,
                        )
                    )
                    break
                measurements: list[LlcrMeasurement] = []
                output_column_start = corrected_start if stage_index == 0 else delta_start
                if output_column_start is None:
                    diagnostics.append(
                        _diagnostic(
                            "stage_not_supported",
                            "A post-initial LLCR stage requires ΔR columns.",
                            section.group_label,
                            stage.source_step,
                        )
                    )
                    break
                for point_offset, point in enumerate(points):
                    row = stage_start + point_offset
                    if _text(sheet.cell(row, 3).value) != point:
                        diagnostics.append(
                            _diagnostic(
                                "point_mapping_conflict",
                                f"Expected point {point} is missing from {sheet_name}.",
                                section.group_label,
                                stage.source_step,
                            )
                        )
                        break
                    for sample_index in range(1, section.sample_count + 1):
                        raw_cell = sheet.cell(row, 3 + sample_index)
                        raw = _decimal(raw_cell.value)
                        if raw is None:
                            diagnostics.append(
                                _diagnostic(
                                    "required_measurement_missing",
                                    f"Missing LLCR measurement at {sheet_name}!{raw_cell.coordinate}.",
                                    section.group_label,
                                    stage.source_step,
                                )
                            )
                            break
                        corrected = raw - bulk
                        initial_key = (sample_index, point)
                        if stage_index == 0:
                            initial_values[initial_key] = corrected
                            value = corrected
                        else:
                            initial = initial_values.get(initial_key)
                            if initial is None:
                                diagnostics.append(
                                    _diagnostic(
                                        "initial_measurement_missing",
                                        f"Initial value for {point} sample {sample_index} is missing.",
                                        section.group_label,
                                        stage.source_step,
                                    )
                                )
                                break
                            value = corrected - initial
                        output_cell = sheet.cell(row, output_column_start + sample_index - 1)
                        measurements.append(
                            LlcrMeasurement(
                                sample_index=sample_index,
                                position=point,
                                value=value,
                                unit="mΩ",
                                source_sheet=sheet_name,
                                source_cell=output_cell.coordinate,
                                raw_value=raw,
                                raw_unit="mΩ",
                                raw_source_cell=raw_cell.coordinate,
                            )
                        )
                if diagnostics:
                    break
                key = (section.confirmed_group_id, stage.confirmed_row_id, stage.source_step.strip())
                accumulator = accumulators.setdefault(
                    key,
                    {
                        "section": section,
                        "stage": stage,
                        "stage_index": stage_index,
                        "requirement": requirement,
                        "measurements": [],
                        "ranges": [],
                    },
                )
                if accumulator["requirement"] != requirement:
                    diagnostics.append(
                        _diagnostic(
                            "requirement_conflict",
                            "LLCR categories disagree on the Matrix requirement.",
                            section.group_label,
                            stage.source_step,
                        )
                    )
                    break
                accumulator["measurements"].extend(measurements)
                start = measurements[0].source_cell
                end = measurements[-1].source_cell
                accumulator["ranges"].append(f"{sheet_name}!{start}:{end}")
                current_row += len(points)
            if diagnostics:
                break
        if diagnostics:
            break

    if diagnostics:
        return [], diagnostics
    entries = [_entry_from_accumulator(key, value) for key, value in accumulators.items()]
    entries.sort(key=lambda item: (_group_sort(item.group_label), item.matrix_step_sequence, item.matrix_step_token))
    if not entries:
        diagnostics.append(_diagnostic("no_llcr_results", "No LLCR result rows were found."))
    return entries, diagnostics


def _entry_from_accumulator(key, value) -> LlcrResultEntry:
    section = value["section"]
    stage = value["stage"]
    stage_index = value["stage_index"]
    comparator, limit, display_requirement = value["requirement"]
    measurements = tuple(value["measurements"])
    values = [measurement.value for measurement in measurements]
    maximum = max(values)
    passed = maximum <= limit if comparator == "<=" else maximum < limit
    outcome = "pass" if passed else "fail"
    token = stage.source_step.strip()
    return LlcrResultEntry(
        result_id=f"{section.confirmed_group_id}:{stage.confirmed_row_id}:{token}",
        confirmed_group_id=section.confirmed_group_id,
        group_label=section.group_label,
        confirmed_row_id=stage.confirmed_row_id,
        matrix_step_sequence=_step_sequence(token),
        matrix_step_token=token,
        stage="initial" if stage_index == 0 else "delta",
        stage_label=_record_stage_label(stage.label, stage_index),
        requirement=display_requirement,
        requirement_comparator=comparator,
        requirement_limit=limit,
        requirement_unit="mΩ",
        measurements=measurements,
        summary_min=min(values),
        summary_max=maximum,
        summary_average=mean(values),
        provisional_outcome=outcome,
        source_range=", ".join(value["ranges"]),
    )


def _parse_requirement(
    value: str,
    *,
    stage_index: int,
) -> tuple[str, Decimal, str] | None:
    normalized = " ".join(_text(value).replace("；", ";").split())
    initial_marker = re.search(r"\binitial\b", normalized, re.IGNORECASE)
    delta_marker = re.search(r"(?:Δ|∆)\s*R|delta\s*r", normalized, re.IGNORECASE)
    marker = initial_marker if stage_index == 0 else delta_marker
    if marker is not None:
        clause_end = normalized.find(";", marker.end())
        match = _REQUIREMENT.search(
            normalized,
            marker.end(),
            len(normalized) if clause_end < 0 else clause_end,
        )
    elif stage_index == 0 and delta_marker is not None:
        return None
    elif stage_index > 0 and initial_marker is not None:
        return None
    else:
        match = _REQUIREMENT.search(normalized)
    if match is None:
        return None
    source_comparator = match.group("comparator")
    comparator = "<=" if source_comparator in {"<=", "≤"} else "<"
    limit = Decimal(match.group("limit"))
    unit = match.group("unit").lower().replace("Ω", "ω").replace("Ω", "ω")
    if unit.startswith(("u", "µ", "μ")):
        limit *= Decimal("0.001")
    elif not unit.startswith("m"):
        limit *= Decimal("1000")
    expression = match.group(0).strip()
    if stage_index == 0 and marker is not None:
        display = f"Initial {expression}"
    elif stage_index > 0 and marker is not None:
        delta_value = re.sub(r"^(?:<=|≤|<)\s*", "", expression)
        display_comparator = "≤" if comparator == "<=" else "<"
        display = f"ΔR {display_comparator} {delta_value}"
    elif stage_index == 0 and expression.startswith(("≤", "≥")):
        display = f"Initial {expression}"
    else:
        display = expression
    return comparator, limit, display


def _bulk_average(sheet) -> Decimal | None:
    values = [_decimal(sheet.cell(row, 2).value) for row in range(2, 5)]
    if any(value is None for value in values):
        return None
    return mean(value for value in values if value is not None)


def _decimal(value) -> Decimal | None:
    if value is None or isinstance(value, str) and not value.strip():
        return None
    if isinstance(value, str) and value.startswith("="):
        return None
    try:
        return Decimal(str(value))
    except (InvalidOperation, ValueError):
        return None


def _section_points(section) -> tuple[str, ...]:
    points: list[str] = []
    for row in section.rows:
        if row.contact_id not in points:
            points.append(row.contact_id)
    return tuple(points)


def _record_stage_label(label: str, stage_index: int) -> str:
    value = label.strip()
    if stage_index == 0 and value == "Initial":
        return "Initial LLCR"
    if value == "Final":
        return "Final LLCR"
    return value


def _sheet_name(value: str, used: set[str]) -> str:
    base = re.sub(r"[\\/*?:\[\]]+", "_", value.strip())[:31] or "Points"
    candidate = base
    suffix = 2
    while candidate in used:
        tail = f"_{suffix}"
        candidate = f"{base[:31 - len(tail)]}{tail}"
        suffix += 1
    return candidate


def _normalized_group(value) -> str:
    return re.sub(r"^group\s*", "", _text(value), flags=re.IGNORECASE).strip().casefold()


def _step_sequence(token: str) -> int:
    match = re.match(r"\s*(\d+)", token)
    if match is None:
        raise ValueError(f"Unsupported Matrix Step token: {token}")
    return int(match.group(1))


def _group_sort(value: str):
    match = re.search(r"\d+", value)
    return (int(match.group()) if match else 1_000_000, value.casefold())


def _text(value) -> str:
    return "" if value is None else str(value).strip()


def _diagnostic(code, message, group_label=None, step_token=None):
    return LlcrImportDiagnostic(code, "blocked", message, group_label, step_token)


def _blocked(code: str, message: str) -> LlcrWorkbookInspection:
    return LlcrWorkbookInspection(
        PARSER_PROFILE_VERSION,
        (),
        (),
        (_diagnostic(code, message),),
    )
